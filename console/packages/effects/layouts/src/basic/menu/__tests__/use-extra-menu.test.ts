import type { App } from 'vue';

import type { MenuRecordRaw } from '@tuquet/types';

import { computed, createApp } from 'vue';

import { describe, expect, it, vi } from 'vitest';

import { useExtraMenu } from '../use-extra-menu';

// preferences is a module-level singleton; test uses mutable mock to control layout & expand behavior
const mockPreferences = vi.hoisted(() => ({
  app: { layout: 'sidebar-mixed-nav' },
  sidebar: { expandOnHover: true },
}));

vi.mock('@tuquet/preferences', () => ({
  preferences: mockPreferences,
}));

// useRoute injects route from instance; test provides via holder directly
const routeHolder = vi.hoisted(() => ({
  current: {
    meta: {},
    path: '/',
  } as { meta: Record<string, unknown>; path: string },
}));

vi.mock('vue-router', () => ({
  useRoute: () => routeHolder.current,
}));

vi.mock('@tuquet/stores', () => ({
  useAccessStore: () => ({ accessMenus: [] }),
}));

vi.mock('../use-navigation', () => ({
  useNavigation: () => ({
    navigation: vi.fn(),
    willOpenedByWindow: () => false,
  }),
}));

/**
 * Menu tree generated by generateMenus based on router.getRoutes() real paths:
 * Top-level menus do not have parents; only child menus have parent/parents set.
 * Repro shape where default child route path is empty (both have /cards).
 */
function createMenus(): MenuRecordRaw[] {
  return [
    {
      name: 'Card Management',
      path: '/cards',
      children: [
        {
          name: 'Card List',
          path: '/cards',
          parent: '/cards',
          parents: ['/cards'],
          children: [],
        },
      ],
    },
    {
      name: 'Transaction Management',
      path: '/transactions',
      children: [
        {
          name: 'Standardized Transaction',
          path: '/transactions/normalized',
          parent: '/transactions',
          parents: ['/transactions'],
          children: [],
        },
      ],
    },
  ];
}

let activeApp: App | undefined;

function mountExtraMenu(menus: MenuRecordRaw[]) {
  const holder: { api?: ReturnType<typeof useExtraMenu> } = {};
  const host = document.createElement('div');
  document.body.append(host);
  activeApp = createApp({
    setup() {
      holder.api = useExtraMenu(computed(() => menus));
      return () => null;
    },
  });
  activeApp.mount(host);
  if (!holder.api) {
    throw new Error('useExtraMenu was not mounted');
  }
  return holder.api;
}

function cleanup() {
  activeApp?.unmount();
  activeApp = undefined;
  document.body.innerHTML = '';
  routeHolder.current = { meta: {}, path: '/' };
  mockPreferences.sidebar.expandOnHover = true;
}

function setPath(path: string) {
  routeHolder.current = { meta: {}, path };
}

describe('useExtraMenu', () => {
  it('resolves secondary menu: empty default child path causes identical paths', async () => {
    try {
      setPath('/cards');
      const { extraActiveMenu, extraMenus, sidebarExtraVisible } =
        mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(1);
      });
      expect(extraMenus.value[0]?.name).toBe('Card List');
      expect(extraActiveMenu.value).toBe('/cards');
      expect(sidebarExtraVisible.value).toBe(true);
    } finally {
      cleanup();
    }
  });

  it('resolves peer secondary menu for normal nested paths', async () => {
    try {
      setPath('/transactions/normalized');
      const { extraActiveMenu, extraMenus } = mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(1);
      });
      expect(extraMenus.value[0]?.name).toBe('Standardized Transaction');
      expect(extraActiveMenu.value).toBe('/transactions');
    } finally {
      cleanup();
    }
  });

  it('secondary menu is empty without error when path not in menu tree', async () => {
    try {
      setPath('/non-existent');
      const { extraActiveMenu, extraMenus, sidebarExtraVisible } =
        mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(0);
      });
      expect(extraActiveMenu.value).toBe('');
      // Cannot expand panel without secondary menu; empty panel would occlude content
      expect(sidebarExtraVisible.value).toBe(false);
    } finally {
      cleanup();
    }
  });

  it('does not expand secondary panel when unpinned and path not in menu tree', async () => {
    try {
      mockPreferences.sidebar.expandOnHover = false;
      setPath('/non-existent');
      const { extraMenus, sidebarExtraVisible } = mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(0);
      });
      expect(sidebarExtraVisible.value).toBe(false);
    } finally {
      cleanup();
    }
  });

  it('restores secondary menu based on current path on mouse leave', async () => {
    try {
      mockPreferences.sidebar.expandOnHover = false;
      setPath('/cards');
      const { extraMenus, handleMenuMouseEnter, handleSideMouseLeave } =
        mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(1);
      });

      // Hovering over another top menu replaces secondary menu; revert on mouseleave
      handleMenuMouseEnter(createMenus()[1] as MenuRecordRaw);
      expect(extraMenus.value[0]?.name).toBe('Standardized Transaction');

      handleSideMouseLeave();
      expect(extraMenus.value).toHaveLength(1);
      expect(extraMenus.value[0]?.name).toBe('Card List');
    } finally {
      cleanup();
    }
  });

  it('restores secondary menu on mouseleave based on activePath (hidden detail page)', async () => {
    try {
      mockPreferences.sidebar.expandOnHover = false;
      // Hidden detail page literal path is not in tree; attaches to list page via activePath
      routeHolder.current = {
        meta: { activePath: '/cards' },
        path: '/cards/17',
      };
      const { extraMenus, handleMenuMouseEnter, handleSideMouseLeave } =
        mountExtraMenu(createMenus());

      await vi.waitFor(() => {
        expect(extraMenus.value).toHaveLength(1);
      });
      expect(extraMenus.value[0]?.name).toBe('Card List');

      handleMenuMouseEnter(createMenus()[1] as MenuRecordRaw);
      expect(extraMenus.value[0]?.name).toBe('Standardized Transaction');

      // Should restore secondary menu for activePath after mouseleave rather than clearing
      handleSideMouseLeave();
      expect(extraMenus.value).toHaveLength(1);
      expect(extraMenus.value[0]?.name).toBe('Card List');
    } finally {
      cleanup();
    }
  });
});
